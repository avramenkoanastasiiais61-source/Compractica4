#include <iostream>
#include <cmath>
#include <iomanip>

using namespace std;

int main()
{
    double x;
    double Sum=0;
    int n=0;
    double accuracy=0.0001;
    double a;
    double factorial = 1;
    int i = 1; 
    
    cout << "x = ";
    cin >> x;

    if (x < 0 || x > 4)
    {
        cout << "False, x[0,4]";
    }
    else
    {

    do
    {
        factorial = 1;
        i=1;

        while (i <= 2 * n)
        {
            factorial=factorial*i;
            i++;
        }
        a = pow(-1, n) * pow(x, 2 * n) / factorial;

        Sum=Sum+a;
        n++;
    }
    while (abs(a)>= accuracy);

    cout<<fixed<<setprecision(4);
    cout<<"Sum = " << Sum;
}
}

